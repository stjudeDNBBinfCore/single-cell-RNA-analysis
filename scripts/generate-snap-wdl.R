    "",
    "  output {",
    "    Int cohort_num_samples = num_samples",
    "    Int cohort_total_estimated_cells = total_estimated_cells",
    "  }",
    "}",
    ""
  )
}

main <- function() {
  args <- parse_args(commandArgs(trailingOnly = TRUE))
  body <- gen_chain(MODULES)
  wdl <- paste(c(workflow_header(), indent_block(body, 2L), workflow_footer()), collapse = "\n")
  dir.create(dirname(args$output), recursive = TRUE, showWarnings = FALSE)
  writeLines(wdl, args$output)
  cat("Wrote", normalizePath(args$output, mustWork = FALSE), "\n")
  cat("  Modules:", paste(vapply(MODULES, `[[`, "", "id"), collapse = ", "), "\n")
}

if (sys.nframe() == 0L) main()
