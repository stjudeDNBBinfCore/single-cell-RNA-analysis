indent_block <- function(text, spaces = 2L) {
  pad <- strrep(" ", spaces)
  paste0(pad, gsub("\n", paste0("\n", pad), text, fixed = TRUE))
}

call_inputs <- function(mod, wait_on_ref = NULL) {
  lines <- c(
    "snap_root = snap_root,",
    "container_image = container_image,",
    "notify_email = notify_email,",
    sprintf("cpu = %s,", mod$cpu),
    sprintf("memory_gb = %s,", mod$memory)
  )
  if (!is.na(mod$future)) {
    lines <- c(lines, sprintf("future_globals_gib = %s,", mod$future))
  }
  lines <- c(lines, sprintf("lsf_queue = %s,", mod$queue))
  if (!is.null(wait_on_ref)) {
    lines <- c(lines, sprintf("wait_on = %s,", wait_on_ref))
  }
  paste(lines, collapse = "\n")
}

gen_chain <- function(modules, idx = 1L, path_suffix = "", wait_on_ref = NULL) {
  if (idx > length(modules)) return("")

  mod <- modules[[idx]]
  alias <- paste0(mod$id, path_suffix)
  next_wait_if_run <- paste0(alias, ".done_flag")

  call_block <- sprintf(
    "call snap.%s as %s {\n  input:\n%s\n}",
    mod$task, alias, indent_block(call_inputs(mod, wait_on_ref), 4L)
  )

  run_body <- paste0(
    call_block, "\n",
    gen_chain(modules, idx + 1L, paste0(path_suffix, "_y"), next_wait_if_run)
  )
  skip_body <- gen_chain(modules, idx + 1L, paste0(path_suffix, "_n"), wait_on_ref)

  sprintf(
    "if (%s) {\n%s\n} else {\n%s\n}",
    mod$flag,
    indent_block(run_body, 2L),
    indent_block(skip_body, 2L)
  )
}

