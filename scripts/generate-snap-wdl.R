#!/usr/bin/env Rscript
################################################################################
# generate-snap-wdl.R
#
# Generate wdl/snap.wdl with all downstream modules optional (Sprocket 0.30.x).
# Each module runs only when its run_* workflow input is true. Skipped modules
# do not block later modules; wait_on chains to the last completed step.
#
# Usage:
#   Rscript scripts/generate-snap-wdl.R [--output wdl/snap.wdl]
################################################################################

parse_args <- function(args) {
  out <- list(output = "wdl/snap.wdl")
  i <- 1L
  while (i <= length(args)) {
    if (args[[i]] == "--output") {
      i <- i + 1L
      out$output <- args[[i]]
    }
    i <- i + 1L
  }
  out
}

